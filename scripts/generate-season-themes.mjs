for (const [id, season] of Object.entries(seasons)) {
  const theme = {
    name: season.name,
    colors: season.colors,
    tokenColors: tokenColors(season.palette),
  };
  const path = join(themesDir, `${id}-color-theme.json`);
  writeFileSync(path, `${JSON.stringify(theme, null, '\t')}\n`);
  console.log(`Wrote ${path}`);
}
